import { LANGS, ROUTES } from "@/lib/routes";
import { getPublishedArticles } from "@/lib/data/articles";
import {
  articleAbsoluteUrl,
  articleAlternates,
  translatedLangs,
} from "@/lib/seo/articleLanguages";
import { ROUTE_LAST_MODIFIED } from "@/lib/data/routeLastModified";
import { SITE_URL } from "@/lib/constants/site";

const LOW_PRIORITY = new Set(["policy"]);

const priorityFor = (key) => {
  if (LOW_PRIORITY.has(key)) return 0.2;
  if (key === "home") return 1.0;
  return 0.8;
};

const absolute = (path) => `${SITE_URL}${path === "/" ? "/" : path}`;

/**
 * `lib/data/routeLastModified.js` is a snapshot generated by
 * `scripts/build-route-dates.mjs` from local git history — full history is
 * always available on a dev machine, unlike Vercel's build checkout (a
 * shallow clone), where a live `git log -- <path>` lookup was tried and
 * confirmed broken: every route in the deployed sitemap.xml came back with
 * the same (wrong) date, because a shallow clone has no parent commit to
 * diff a boundary commit against. Re-run that script and commit the result
 * when a page's route file changes.
 */
const lastModifiedFor = (path) => ROUTE_LAST_MODIFIED[path] ?? undefined;

export default async function sitemap() {
  const entries = [];

  for (const key of Object.keys(ROUTES)) {
    const languages = Object.fromEntries(
      LANGS.map((lang) => [lang, absolute(ROUTES[key][lang])]),
    );
    languages["x-default"] = absolute(ROUTES[key].fr);

    for (const lang of LANGS) {
      entries.push({
        url: absolute(ROUTES[key][lang]),
        lastModified: lastModifiedFor(ROUTES[key][lang]),
        changeFrequency: key === "news" ? "weekly" : "monthly",
        priority: priorityFor(key),
        alternates: { languages },
      });
    }
  }

  const articles = await getPublishedArticles();
  for (const article of articles) {
    // Only real translations: a French copy served under /en or /ar is
    // noindex (see lib/seo/articleLanguages.js) and stays out of the sitemap.
    const langs = translatedLangs(article);
    const { languages } =
      articleAlternates(article, "fr").alternates;

    for (const lang of langs) {
      entries.push({
        url: articleAbsoluteUrl(article, lang),
        lastModified: article.publishedAt ?? undefined,
        changeFrequency: "weekly",
        priority: 0.6,
        ...(languages ? { alternates: { languages } } : {}),
      });
    }
  }

  return entries;
}
