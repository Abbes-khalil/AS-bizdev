/**
 * One-off generator: turns world-atlas's TopoJSON into a static SVG path
 * dataset scoped to Africa + the Middle East, with pixel centroids for our
 * 14 active markets. Output is plain data (lib/data/marketsMapData.js) — no
 * mapping library ships to the client, only the numbers this script computes.
 *
 *   node scripts/build-markets-map.mjs
 *
 * Re-run only if the active market list changes. world-atlas / topojson-client
 * / d3-geo are dev-only tools for this script, not runtime dependencies.
 */
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

import { geoCentroid, geoMercator, geoPath } from "d3-geo";
import { feature } from "topojson-client";

import topology from "world-atlas/countries-50m.json" with { type: "json" };

// ISO 3166-1 numeric → our stable `key` (must match lib/data/countries.js).
const ACTIVE = {
  "788": "tunisia",
  "504": "morocco",
  "818": "egypt",
  "012": "algeria",
  "384": "ivoryCoast",
  "686": "senegal",
  "566": "nigeria",
  "710": "southAfrica",
  "784": "uae",
  "682": "saudiArabia",
  "634": "qatar",
  "414": "kuwait",
  "048": "bahrain",
  "400": "jordan",
};

const WIDTH = 960;
const HEIGHT = 860;

const world = feature(topology, topology.objects.countries);

// Africa + the Middle East, by bounding box on each country's geographic
// centroid — keeps the map editorial (no stray continents) without
// hand-maintaining a per-country region list.
const inScope = world.features.filter((f) => {
  const [lon, lat] = geoCentroid(f);
  return lon >= -25 && lon <= 65 && lat >= -37 && lat <= 42;
});

const scoped = { type: "FeatureCollection", features: inScope };
const projection = geoMercator().fitExtent(
  [
    [16, 16],
    [WIDTH - 16, HEIGHT - 16],
  ],
  scoped,
);
// 1 decimal place is plenty at the sizes this map renders at, and roughly
// halves the output size versus geoPath's default full float precision.
const path = geoPath(projection).digits(1);

// A handful of territories in the atlas (e.g. Somaliland, Western Sahara)
// carry no ISO numeric id at all — fall back to the array index so every
// shape still gets a distinct React key.
const countries = inScope.map((f, index) => {
  const id = f.id != null ? String(f.id).padStart(3, "0") : `x${index}`;
  const key = ACTIVE[id] ?? null;
  return {
    id,
    key,
    d: path(f),
  };
});

const markets = {};
for (const country of countries) {
  if (!country.key) continue;
  const [cx, cy] = path.centroid(
    inScope.find((f) => String(f.id).padStart(3, "0") === country.id),
  );
  markets[country.key] = { cx: Number(cx.toFixed(1)), cy: Number(cy.toFixed(1)) };
}

const missing = Object.values(ACTIVE).filter((key) => !markets[key]);
if (missing.length) {
  console.error("Missing centroid for:", missing);
  process.exit(1);
}

const out = `/**
 * Generated by scripts/build-markets-map.mjs — do not hand-edit.
 * Africa + Middle East country outlines (Mercator, fitted to the viewBox
 * below) plus pixel centroids for the 14 active markets in countries.js.
 */
export const MAP_VIEWBOX = "0 0 ${WIDTH} ${HEIGHT}";

export const MAP_COUNTRIES = ${JSON.stringify(
  countries.map(({ id, key, d }) => ({ id, key, d })),
)};

export const MARKET_POSITIONS = ${JSON.stringify(markets, null, 2)};
`;

const dest = fileURLToPath(new URL("../lib/data/marketsMapData.js", import.meta.url));
await writeFile(dest, out, "utf8");
console.log(`✓ ${countries.length} country shapes, ${Object.keys(markets).length} active markets → lib/data/marketsMapData.js`);
