/**
 * One-off generator: snapshots each route's last-git-commit date into
 * static data (lib/data/routeLastModified.js), consumed by app/sitemap.js.
 *
 * Why not read git history directly in app/sitemap.js: Vercel's production
 * build checkout is a shallow clone (depth 1), so `git log -- <path>`
 * there has no parent commit to diff a boundary commit against and reports
 * that single fetched commit as the "last change" for every path — every
 * route in the deployed sitemap.xml came back with the same (wrong,
 * today's-deploy) date. Unshallowing at build time (`git fetch
 * --unshallow`) was tried and didn't reliably work in Vercel's build
 * sandbox (network/credentials scoped to the initial checkout only).
 * Local git history is always full, so compute this here once, on a real
 * dev machine, and commit the plain result — no git dependency left at
 * either build or request time.
 *
 *   node scripts/build-route-dates.mjs
 *
 * Re-run whenever a page's route file changes, ideally right before
 * committing that change, so the snapshot stays close to accurate. A stale
 * entry degrades gracefully (an old-but-real date), which is still more
 * honest than the uniform-today bug this replaces.
 */
import { execSync } from "node:child_process";
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

import { LANGS, ROUTES } from "../lib/routes.js";

const pageFileFor = (path) => `app${path === "/" ? "" : path}/page.jsx`;

const lastCommitDate = (file) => {
  try {
    return (
      execSync(`git log -1 --format=%aI -- "${file}"`, {
        encoding: "utf8",
      }).trim() || null
    );
  } catch {
    return null;
  }
};

const entries = {};
for (const key of Object.keys(ROUTES)) {
  for (const lang of LANGS) {
    const path = ROUTES[key][lang];
    const date = lastCommitDate(pageFileFor(path));
    if (date) entries[path] = date;
  }
}

const out = `/**
 * Generated by scripts/build-route-dates.mjs — do not hand-edit.
 * Each static route's last-git-commit date at generation time, keyed by
 * URL path. See that script for why this is a snapshot instead of a
 * runtime git lookup.
 */
export const ROUTE_LAST_MODIFIED = ${JSON.stringify(entries, null, 2)};
`;

const dest = fileURLToPath(new URL("../lib/data/routeLastModified.js", import.meta.url));
await writeFile(dest, out, "utf8");
console.log(`✓ ${Object.keys(entries).length} route dates → lib/data/routeLastModified.js`);
